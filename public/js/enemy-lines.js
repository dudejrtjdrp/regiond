  /** 결정론 해시(FNV-1a 32비트) — 같은 글자면 어느 화면에서나 같은 수다. */
  function hash(str) {
    var h = 2166136261;
    var s = String(str == null ? '' : str);
    for (var i = 0; i < s.length; i++) {
      h ^= s.charCodeAt(i);
      /* 32비트로 접어 두지 않으면 큰 수가 되며 브라우저마다 끝자리가 갈린다 */
      h = (h + (h << 1) + (h << 4) + (h << 7) + (h << 8) + (h << 24)) >>> 0;
    }
    return h >>> 0;
  }

